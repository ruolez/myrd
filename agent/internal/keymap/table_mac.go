package keymap

// Mac maps HID usage (page 0x07) → CGKeyCode (Carbon kVK_*). Owned by the
// macOS backend. PC-only keys follow Apple extended keyboards:
// PrintScreen/ScrollLock/Pause → F13/F14/F15, Insert → Help, NumLock → Clear.
var Mac = Table{
	// Letters a..z (0x04..0x1D)
	0x04: {Code: 0x00}, 0x05: {Code: 0x0B}, 0x06: {Code: 0x08}, 0x07: {Code: 0x02},
	0x08: {Code: 0x0E}, 0x09: {Code: 0x03}, 0x0A: {Code: 0x05}, 0x0B: {Code: 0x04},
	0x0C: {Code: 0x22}, 0x0D: {Code: 0x26}, 0x0E: {Code: 0x28}, 0x0F: {Code: 0x25},
	0x10: {Code: 0x2E}, 0x11: {Code: 0x2D}, 0x12: {Code: 0x1F}, 0x13: {Code: 0x23},
	0x14: {Code: 0x0C}, 0x15: {Code: 0x0F}, 0x16: {Code: 0x01}, 0x17: {Code: 0x11},
	0x18: {Code: 0x20}, 0x19: {Code: 0x09}, 0x1A: {Code: 0x0D}, 0x1B: {Code: 0x07},
	0x1C: {Code: 0x10}, 0x1D: {Code: 0x06},

	// Digits 1..9, 0 (0x1E..0x27)
	0x1E: {Code: 0x12}, 0x1F: {Code: 0x13}, 0x20: {Code: 0x14}, 0x21: {Code: 0x15},
	0x22: {Code: 0x17}, 0x23: {Code: 0x16}, 0x24: {Code: 0x1A}, 0x25: {Code: 0x1C},
	0x26: {Code: 0x19}, 0x27: {Code: 0x1D},

	0x28: {Code: 0x24}, // Enter → Return
	0x29: {Code: 0x35}, // Escape
	0x2A: {Code: 0x33}, // Backspace → Delete
	0x2B: {Code: 0x30}, // Tab
	0x2C: {Code: 0x31}, // Space
	0x2D: {Code: 0x1B}, // Minus
	0x2E: {Code: 0x18}, // Equal
	0x2F: {Code: 0x21}, // BracketLeft
	0x30: {Code: 0x1E}, // BracketRight
	0x31: {Code: 0x2A}, // Backslash
	0x32: {Code: 0x2A}, // IntlHash (ISO #~ sits on the Backslash code on Mac)
	0x33: {Code: 0x29}, // Semicolon
	0x34: {Code: 0x27}, // Quote
	0x35: {Code: 0x32}, // Backquote
	0x36: {Code: 0x2B}, // Comma
	0x37: {Code: 0x2F}, // Period
	0x38: {Code: 0x2C}, // Slash
	0x39: {Code: 0x39}, // CapsLock

	// F1..F12 (0x3A..0x45)
	0x3A: {Code: 0x7A}, 0x3B: {Code: 0x78}, 0x3C: {Code: 0x63}, 0x3D: {Code: 0x76},
	0x3E: {Code: 0x60}, 0x3F: {Code: 0x61}, 0x40: {Code: 0x62}, 0x41: {Code: 0x64},
	0x42: {Code: 0x65}, 0x43: {Code: 0x6D}, 0x44: {Code: 0x67}, 0x45: {Code: 0x6F},

	0x46: {Code: 0x69}, // PrintScreen → F13
	0x47: {Code: 0x6B}, // ScrollLock → F14
	0x48: {Code: 0x71}, // Pause → F15
	0x49: {Code: 0x72}, // Insert → Help
	0x4A: {Code: 0x73}, // Home
	0x4B: {Code: 0x74}, // PageUp
	0x4C: {Code: 0x75}, // Delete → ForwardDelete
	0x4D: {Code: 0x77}, // End
	0x4E: {Code: 0x79}, // PageDown
	0x4F: {Code: 0x7C}, // ArrowRight
	0x50: {Code: 0x7B}, // ArrowLeft
	0x51: {Code: 0x7D}, // ArrowDown
	0x52: {Code: 0x7E}, // ArrowUp

	// Keypad
	0x53: {Code: 0x47},                                         // NumLock → KeypadClear
	0x54: {Code: 0x4B},                                         // NumpadDivide
	0x55: {Code: 0x43},                                         // NumpadMultiply
	0x56: {Code: 0x4E},                                         // NumpadSubtract
	0x57: {Code: 0x45},                                         // NumpadAdd
	0x58: {Code: 0x4C},                                         // NumpadEnter
	0x59: {Code: 0x53}, 0x5A: {Code: 0x54}, 0x5B: {Code: 0x55}, // Numpad1..3
	0x5C: {Code: 0x56}, 0x5D: {Code: 0x57}, 0x5E: {Code: 0x58}, // Numpad4..6
	0x5F: {Code: 0x59}, 0x60: {Code: 0x5B}, 0x61: {Code: 0x5C}, // Numpad7..9
	0x62: {Code: 0x52}, // Numpad0
	0x63: {Code: 0x41}, // NumpadDecimal
	0x64: {Code: 0x0A}, // IntlBackslash → ISO_Section
	0x65: {Code: 0x6E}, // ContextMenu → ContextualMenu
	0x67: {Code: 0x51}, // NumpadEqual

	// F13..F20 (0x68..0x6F)
	0x68: {Code: 0x69}, 0x69: {Code: 0x6B}, 0x6A: {Code: 0x71}, 0x6B: {Code: 0x6A},
	0x6C: {Code: 0x40}, 0x6D: {Code: 0x4F}, 0x6E: {Code: 0x50}, 0x6F: {Code: 0x5A},

	0x7F: {Code: 0x4A}, // AudioVolumeMute
	0x80: {Code: 0x48}, // AudioVolumeUp
	0x81: {Code: 0x49}, // AudioVolumeDown
	0x85: {Code: 0x5F}, // NumpadComma → JIS_KeypadComma
	0x87: {Code: 0x5E}, // IntlRo → JIS_Underscore
	0x89: {Code: 0x5D}, // IntlYen → JIS_Yen
	0x90: {Code: 0x68}, // Lang1 → JIS_Kana
	0x91: {Code: 0x66}, // Lang2 → JIS_Eisu

	// Modifiers
	0xE0: {Code: 0x3B}, // ControlLeft
	0xE1: {Code: 0x38}, // ShiftLeft
	0xE2: {Code: 0x3A}, // AltLeft → Option
	0xE3: {Code: 0x37}, // MetaLeft → Command
	0xE4: {Code: 0x3E}, // ControlRight
	0xE5: {Code: 0x3C}, // ShiftRight
	0xE6: {Code: 0x3D}, // AltRight → RightOption
	0xE7: {Code: 0x36}, // MetaRight → RightCommand
}
